//! Bakes what this web launcher shares with the desktop one: the pinned Minecraft version
//! (research-lock.json, read like launcher/src/sources.rs's `Pins::read`) and, when a release
//! build is made for this fork, the repository and version (HORIZON_GAME_REPO and friends, as
//! launcher/build.rs bakes them for the desktop launcher).

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let dir = env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
    for name in ["HORIZON_GAME_REPO", "HORIZON_LAUNCHER_VERSION", "HORIZON_LAUNCHER_TAG"] {
        println!("cargo:rerun-if-env-changed={name}");
    }
    let lock = Path::new(&dir).join("../../research-lock.json");
    println!("cargo:rerun-if-changed={}", lock.display());
    let text = fs::read_to_string(&lock)
        .unwrap_or_else(|e| panic!("{}: {e}", lock.display()));
    let json: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("{}: {e}", lock.display()));
    let game = &json["minecraft"];
    let strings = |key: &str| -> String {
        game[key]
            .as_str()
            .unwrap_or_else(|| panic!("research-lock.json has no minecraft.{key}"))
            .to_string()
    };
    let version = strings("version");
    let client = strings("client_sha1");
    // The version JSON's sha1, then the earlier ones Mojang republished, as `Pins` keeps them.
    let mut manifests = vec![strings("manifest_sha1")];
    if let Some(list) = game["accepted_manifest_sha1"].as_array() {
        manifests.extend(list.iter().filter_map(|v| v.as_str().map(String::from)));
    }
    // The asset indexes (id 34) of those republished version JSONs, for the Verify page.
    let mut indexes = Vec::new();
    if let Some(list) = game["accepted_asset_index_sha1"].as_array() {
        indexes.extend(list.iter().filter_map(|v| v.as_str().map(String::from)));
    }
    let quote = |list: &[String]| {
        list.iter()
            .map(|s| format!("    \"{s}\","))
            .collect::<Vec<_>>()
            .join("\n")
    };
    let out = format!(
        "// Generated by build.rs from research-lock.json: the pins the desktop launcher's\n\
         // `Pins::read` holds, for the same checks in the browser.\n\
         pub const MC_VERSION: &str = \"{version}\";\n\
         pub const MC_CLIENT_SHA1: &str = \"{client}\";\n\
         pub const MC_MANIFESTS: &[&str] = &[\n{}\n];\n\
         pub const MC_ASSET_INDEXES: &[&str] = &[\n{}\n];\n",
        quote(&manifests),
        quote(&indexes),
    );
    let out_dir = env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("pins.rs"), out)
        .expect("writing OUT_DIR/pins.rs");
}
